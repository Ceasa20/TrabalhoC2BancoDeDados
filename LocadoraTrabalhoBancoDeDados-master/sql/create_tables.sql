CREATE TABLE LABDATABASE.CLIENTES (
    CPF VARCHAR2(11) NOT NULL,
    NOME VARCHAR2(255) NOT NULL,
    TELEFONE VARCHAR2(20),
    ATIVO CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT CLIENTES_ATIVO_CK CHECK (ATIVO IN ('S', 'N')),
    CONSTRAINT CLIENTES_PK PRIMARY KEY (CPF)
);

CREATE TABLE LABDATABASE.CARROS (
    PLACA VARCHAR2(7) NOT NULL,
    MODELO VARCHAR2(100) NOT NULL,
    MARCA VARCHAR2(100) NOT NULL,
    VALOR_DIARIA NUMBER(10,2) NOT NULL,
    ATIVO CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT CARROS_ATIVO_CK CHECK (ATIVO IN ('S', 'N')),
    CONSTRAINT CARROS_PK PRIMARY KEY (PLACA)
);

CREATE TABLE LABDATABASE.LOCACAO (
    CODIGO_LOCACAO NUMBER NOT NULL,
    DATA_INICIO_LOCACAO DATE NOT NULL,
    DATA_PREVISAO_LOCACAO DATE NOT NULL,
    DATA_FIM_LOCACAO DATE,
    DIAS_LOCACAO NUMBER(5) NOT NULL,
    VALOR_TOTAL NUMBER(10,2) NOT NULL,
    CPF VARCHAR2(11) NOT NULL,
    PLACA VARCHAR2(7) NOT NULL,
    CONSTRAINT LOCACOES_PK PRIMARY KEY (CODIGO_LOCACAO),
    CONSTRAINT CLIENTES_LOCACOES_FK FOREIGN KEY (CPF)
        REFERENCES LABDATABASE.CLIENTES (CPF),
    CONSTRAINT CARROS_LOCACOES_FK FOREIGN KEY (PLACA)
        REFERENCES LABDATABASE.CARROS (PLACA)
);

CREATE SEQUENCE LABDATABASE.LOCACAO_CODIGO_LOCACAO_SEQ;
